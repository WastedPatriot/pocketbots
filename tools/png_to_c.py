#!/usr/bin/env python3
"""Turn assets/bots.json (and any PNGs it names) into firmware C.

Usage:
  python3 tools/png_to_c.py                 # write the generated sources
  python3 tools/png_to_c.py --check         # fail if the tree is stale
  python3 tools/png_to_c.py --placeholders  # rewrite the stand-in PNGs
  python3 tools/png_to_c.py --self-test     # convert the stand-ins in a temp dir

A bot with no "image" is drawn by the firmware. A bot with
"image": "avatars/cyber.png" (path relative to assets/) is baked in
as LVGL ARGB8888, little-endian B,G,R,A, and shown instead.

The generated files are committed so a firmware build does not need
Python. Re-run this after you edit bots.json.
"""

from __future__ import annotations

import argparse
import io
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
JSON_PATH = ASSETS / "bots.json"
OUT_H = ROOT / "firmware" / "src" / "generated" / "bots.gen.h"
OUT_C = ROOT / "firmware" / "src" / "generated" / "bots.gen.c"

sys.path.insert(0, str(ROOT / "tools"))
from marks import PALETTE, SHAPES, parse_color, render  # noqa: E402

SHAPE_ENUM = {
    "circle": "PB_SHAPE_CIRCLE",
    "cloud": "PB_SHAPE_CLOUD",
    "squircle": "PB_SHAPE_SQUIRCLE",
    "plus": "PB_SHAPE_PLUS",
    "peanut": "PB_SHAPE_PEANUT",
    "blob": "PB_SHAPE_BLOB",
    "flower": "PB_SHAPE_FLOWER",
    "drop": "PB_SHAPE_DROP",
    "pill": "PB_SHAPE_PILL",
    "triangle": "PB_SHAPE_TRIANGLE",
    "house": "PB_SHAPE_HOUSE",
    "star": "PB_SHAPE_STAR",
    "hexagon": "PB_SHAPE_HEXAGON",
}


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def png_to_bgra(path: Path, size: int = 176) -> tuple[int, int, bytes]:
    from PIL import Image

    im = Image.open(path).convert("RGBA")
    # Fit inside the mark box, keep the aspect, pad with nothing.
    im.thumbnail((size, size), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.paste(im, ((size - im.width) // 2, (size - im.height) // 2), im)
    raw = bytearray()
    for r, g, b, a in canvas.getdata():
        raw += bytes((b, g, r, a))
    return size, size, bytes(raw)


def emit(data: dict) -> tuple[str, str]:
    images: list[tuple[str, int, int, bytes]] = []
    rows = []
    for bot in data["bots"]:
        shape = bot["shape"]
        if shape not in SHAPE_ENUM:
            raise SystemExit(f"{bot.get('id')}: unknown shape {shape!r}. known: {', '.join(SHAPES)}")
        color = parse_color(str(bot["color"]))
        image = bot.get("image") or None
        sym = "NULL"
        if image:
            path = (ASSETS / image).resolve()
            if not path.is_file():
                raise SystemExit(f"{bot.get('id')}: image not found: {path}")
            w, h, blob = png_to_bgra(path)
            ident = "pb_img_" + "".join(ch if ch.isalnum() else "_" for ch in bot["id"])
            images.append((ident, w, h, blob))
            sym = "&" + ident
        hidden = "true" if bot.get("hidden") else "false"
        rows.append(
            "    { "
            + ", ".join(
                [
                    c_string(bot["id"]),
                    c_string(bot["name"]),
                    c_string(bot["subtitle"]),
                    SHAPE_ENUM[shape],
                    f"0x{color:06X}",
                    hidden,
                    sym,
                ]
            )
            + " },"
        )

    header = f"""/* Generated by tools/png_to_c.py from assets/bots.json. Do not edit. */
#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "lvgl.h"

#ifdef __cplusplus
extern "C" {{
#endif

#define PB_CFG_BRIGHTNESS {int(data["brightness"])}
#define PB_CFG_AMBIENT_BRIGHTNESS {int(data["ambient_brightness"])}
#define PB_CFG_AMBIENT_AFTER_S {int(data["ambient_after_s"])}
#define PB_CFG_SLEEP_AFTER_S {int(data["sleep_after_s"])}

typedef enum {{
    PB_SHAPE_CIRCLE = 0,
    PB_SHAPE_CLOUD,
    PB_SHAPE_SQUIRCLE,
    PB_SHAPE_PLUS,
    PB_SHAPE_PEANUT,
    PB_SHAPE_BLOB,
    PB_SHAPE_FLOWER,
    PB_SHAPE_DROP,
    PB_SHAPE_PILL,
    PB_SHAPE_TRIANGLE,
    PB_SHAPE_HOUSE,
    PB_SHAPE_STAR,
    PB_SHAPE_HEXAGON,
    PB_SHAPE_COUNT
}} pb_shape_t;

typedef struct {{
    const char *id;
    const char *name;
    const char *subtitle;
    pb_shape_t shape;
    uint32_t color;
    bool hidden;
    const lv_image_dsc_t *image;
}} pb_bot_t;

extern const pb_bot_t pb_bots[];
extern const unsigned pb_bot_count;

#ifdef __cplusplus
}}
#endif
"""

    body = ["/* Generated by tools/png_to_c.py from assets/bots.json. Do not edit. */", '#include "generated/bots.gen.h"', ""]
    for ident, w, h, blob in images:
        body.append(f"static const uint8_t {ident}_map[] = {{")
        line = []
        for i, byte in enumerate(blob):
            line.append(f"0x{byte:02X}")
            if len(line) == 16:
                body.append("    " + ", ".join(line) + ",")
                line = []
        if line:
            body.append("    " + ", ".join(line) + ",")
        body.append("};")
        body.append(f"static const lv_image_dsc_t {ident} = {{")
        body.append("    .header = {")
        body.append("        .magic = LV_IMAGE_HEADER_MAGIC,")
        body.append("        .cf = LV_COLOR_FORMAT_ARGB8888,")
        body.append(f"        .w = {w},")
        body.append(f"        .h = {h},")
        body.append(f"        .stride = {w * 4},")
        body.append("    },")
        body.append(f"    .data_size = {len(blob)},")
        body.append(f"    .data = {ident}_map,")
        body.append("};")
        body.append("")
    body.append("const pb_bot_t pb_bots[] = {")
    body.extend(rows)
    body.append("};")
    body.append(f"const unsigned pb_bot_count = {len(rows)};")
    body.append("")
    return header, "\n".join(body) + "\n"


def write_placeholders() -> None:
    out = ASSETS / "avatars"
    out.mkdir(parents=True, exist_ok=True)
    specs = [("cyber.placeholder.png", "hexagon", "blue"), ("vik.placeholder.png", "cloud", "orange")]
    for name, shape, color in specs:
        img = render(shape, parse_color(color), 176, placeholder=True)
        # Flatten onto the firmware background so a file browser shows the caption.
        from PIL import Image

        bg = Image.new("RGBA", img.size, (0x14, 0x14, 0x16, 255))
        flat = Image.alpha_composite(bg, img).convert("RGB")
        flat.save(out / name)
        print(f"wrote {out / name}")
    note = out / "PLACEHOLDERS"
    note.write_text(
        "These PNGs are stand-ins. The word PLACEHOLDER is burned into them\n"
        "so they cannot be mistaken for finished faces.\n"
        "\n"
        "The firmware does not use them. Cyber and Vik are drawn in code\n"
        "(see assets/bots.json; leave \"image\" unset for the animated mark).\n"
        "\n"
        "To drop in your own:\n"
        "  1. Export a square PNG. Transparent background is fine.\n"
        "  2. Put it in this folder.\n"
        "  3. In assets/bots.json set \"image\": \"avatars/your.png\".\n"
        "  4. python3 tools/png_to_c.py\n"
        "  5. Rebuild the firmware.\n"
        "\n"
        "A PNG replaces the drawn shape. It will not blink. It still bobs.\n"
    )


def self_test() -> None:
    import tempfile

    data = json.loads(JSON_PATH.read_text())
    data["bots"] = [
        {
            "id": "cyber",
            "name": "Cyber",
            "subtitle": "placeholder",
            "shape": "hexagon",
            "color": "blue",
            "hidden": False,
            "image": "avatars/cyber.placeholder.png",
        }
    ]
    # emit() reads images relative to ASSETS, so this works in place.
    header, source = emit(data)
    if "pb_img_cyber" not in source or "LV_COLOR_FORMAT_ARGB8888" not in source:
        raise SystemExit("self-test: image was not embedded")
    if source.count("0x") < 1000:
        raise SystemExit("self-test: embedded image looks empty")
    print(f"self-test ok, {len(source)} bytes of C")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--placeholders", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.placeholders or args.self_test:
        write_placeholders()
    if args.self_test:
        self_test()
        if not args.check and args.self_test and not args.placeholders:
            # self-test rewrote placeholders as a side effect of needing them,
            # which is what we want, and does not touch the generated sources.
            return
    data = json.loads(JSON_PATH.read_text())
    for key in ("brightness", "ambient_brightness", "ambient_after_s", "sleep_after_s", "bots"):
        if key not in data:
            raise SystemExit(f"bots.json missing {key}")
    header, source = emit(data)
    if args.check:
        cur_h = OUT_H.read_text() if OUT_H.exists() else ""
        cur_c = OUT_C.read_text() if OUT_C.exists() else ""
        if cur_h != header or cur_c != source:
            raise SystemExit("generated bot sources are stale. run: python3 tools/png_to_c.py")
        print("bots.gen.h / bots.gen.c match assets/bots.json")
        return
    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text(header)
    OUT_C.write_text(source)
    print(f"wrote {OUT_H.relative_to(ROOT)} and {OUT_C.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
